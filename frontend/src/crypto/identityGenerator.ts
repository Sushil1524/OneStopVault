function secureRandomIndex(max: number): number {
  const buf = new Uint32Array(1);
  crypto.getRandomValues(buf);
  return buf[0] % max;
}

function capitalizeWord(word: string): string {
  if (!word) return '';
  return word.charAt(0).toUpperCase() + word.slice(1);
}

/**
 * Generate a cryptographically random, clean ASCII username
 */
export function generateSecureUsername(options: GenerateUsernameOptions = {}): string {
  const {
    style = 'words',
    separator = '',
    capitalize = true,
    digits = 'two',
    length = 12,
  } = options;

  if (style === 'random') {
    // Alphanumeric, guaranteed to start with a letter
    const letters = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
    const all = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
    const len = Math.max(6, Math.min(32, length));
    const randomBuf = new Uint32Array(len);
    crypto.getRandomValues(randomBuf);

    let result = letters[randomBuf[0] % letters.length];
    for (let i = 1; i < len; i++) {
      result += all[randomBuf[i] % all.length];
    }
    return result;
  }

  // Word-based: [Adjective] + [Separator] + [Noun]
  const adj = IDENTITY_ADJECTIVES[secureRandomIndex(IDENTITY_ADJECTIVES.length)];
  const noun = IDENTITY_NOUNS[secureRandomIndex(IDENTITY_NOUNS.length)];

  const first = capitalize ? capitalizeWord(adj) : adj;
  const second = capitalize ? capitalizeWord(noun) : noun;
  let handle = `${first}${separator}${second}`;

  if (digits === 'two') {
    // 10 to 99
    const num = 10 + secureRandomIndex(90);
    handle += num.toString();
  } else if (digits === 'three') {
    // 100 to 999
    const num = 100 + secureRandomIndex(900);
    handle += num.toString();
  }

  return handle;
}

/**
 * Generate a privacy-preserving email address or sub-addressed alias
 */
export function generateSecureEmail(options: GenerateEmailOptions = {}): string {
  const {
    mode = 'domain',
    plusEmail = '',
    domain = 'gmail.com',
    usernameOptions = {},
  } = options;

  // For emails, lowercase tag without spaces or unusual symbols is standard
  const tag = generateSecureUsername({
    ...usernameOptions,
    capitalize: false,
    separator: usernameOptions.separator === '.' || usernameOptions.separator === '_' ? usernameOptions.separator : '',
  }).toLowerCase();

  if (mode === 'plus' && plusEmail.trim().includes('@')) {
    const raw = plusEmail.trim();
    const atIdx = raw.indexOf('@');
    const localPart = raw.substring(0, atIdx).trim();
    const hostPart = raw.substring(atIdx + 1).trim().toLowerCase();

    if (localPart && hostPart) {
      // Strip any existing plus tag from user's base email
      const baseUser = localPart.split('+')[0].toLowerCase();
      return `${baseUser}+${tag}@${hostPart}`;
    }
  }

  const cleanDomain = domain.replace(/^@/, '').trim().toLowerCase() || 'gmail.com';
  return `${tag}@${cleanDomain}`;
}
