export type UsernameStyle = 'words' | 'random';
export type UsernameSeparator = '' | '_' | '-' | '.';
export type SuffixDigits = 'none' | 'two' | 'three';

export interface GenerateUsernameOptions {
  style?: UsernameStyle;
  separator?: UsernameSeparator;
  capitalize?: boolean;
  digits?: SuffixDigits;
  length?: number; // for random style (6-32)
}

export interface GenerateEmailOptions {
  mode?: 'plus' | 'domain';
  plusEmail?: string;     // e.g. user@gmail.com -> user+tag@gmail.com
  domain?: string;        // e.g. 'gmail.com', 'proton.me', 'duck.com'
  usernameOptions?: GenerateUsernameOptions;
}

