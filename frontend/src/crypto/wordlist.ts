export interface PassphraseOptions {
  wordCount?: number;           // Default: 4 words (range 3 to 7)
  separator?: string;           // '-', '_', '.', ' ', '/'
  capitalize?: boolean;         // TitleCase words
  includeNumber?: boolean;      // Append 2-digit random number
}

/**
 * Generate a cryptographically secure passphrase using crypto.getRandomValues.
 * Uses exact power-of-2 bitmask (2048 - 1 = 2047) to eliminate modulo bias.
 */
export function generateSecurePassphrase(options: PassphraseOptions = {}): string {
  const {
    wordCount = 4,
    separator = '-',
    capitalize = false,
    includeNumber = true,
  } = options;

  const count = Math.max(3, Math.min(8, wordCount));
  const randomIndices = new Uint32Array(count);
  crypto.getRandomValues(randomIndices);

  const selectedWords: string[] = [];
  for (let i = 0; i < count; i++) {
    // 2048 is 2^11, so randomIndices[i] & 2047 has exactly zero modulo bias
    const index = randomIndices[i] & 2047;
    let word = PASSPHRASE_WORDLIST[index];
    if (capitalize) {
      word = word.charAt(0).toUpperCase() + word.slice(1);
    }
    selectedWords.push(word);
  }

  let result = selectedWords.join(separator);

  if (includeNumber) {
    const numRandom = new Uint32Array(1);
    crypto.getRandomValues(numRandom);
    const num = (numRandom[0] % 90) + 10; // Random 2-digit number 10-99
    result += separator !== '' ? `${separator}${num}` : `${num}`;
  }

  return result;
}

/**
 * Calculate estimated entropy in bits
 */
export function calculatePassphraseEntropy(options: PassphraseOptions = {}): number {
  const {
    wordCount = 4,
    includeNumber = true,
  } = options;
  let entropy = wordCount * 11;
  if (includeNumber) {
    entropy += 6.5; // ~6.5 bits for 10-99
  }
  return Math.round(entropy);
}
